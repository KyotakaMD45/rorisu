export default {
  name: 'list',
  aliases: ['help', 'aide', 'menu'],
  description: 'Affiche la liste des commandes disponibles.',
  async execute({ sendReply, config, storage }) {
    const prefix = config.prefixes[0];
    const prefixes = config.prefixes.join(' / ');
    const autoStatus = await storage.get('feature:auto_status') === true ? '✅ Activé' : '❌ Désactivé';
    const autoUpdate = await storage.get('feature:auto_update') === true ? '✅ Activée' : '❌ Désactivée';
    const menu = [
      `╭━━〔 *${config.botName} • MENU* 〕━━╮`,
      `┃ 🔹 Préfixe(s) : ${prefixes}`,
      `┃ 🔹 Commandes : ${prefix}menu`,
      '┣━━━━━━━━━━━━━━━━━━',
      '┃ ✨ *INFORMATIONS*',
      `┃ ${prefix}alive — statut et options du bot`,
      `┃ ${prefix}ping — vérifier la latence`,
      '┣━━━━━━━━━━━━━━━━━━',
      '┃ 🧰 *OUTILS & MÉDIAS*',
      `┃ ${prefix}afk [raison|off] — gérer son absence`,
      `┃ ${prefix}poll question, choix 1, choix 2`,
      `┃ ${prefix}react emoji — réagir à un message cité`,
      `┃ ${prefix}delete / ${prefix}dlt — supprimer un message cité`,
      `┃ ${prefix}sticker / ${prefix}s — créer un autocollant`,
      '┣━━━━━━━━━━━━━━━━━━',
      '┃ 👥 *GESTION DE GROUPE* (admin requis)',
      `┃ ${prefix}ginfo — informations du groupe`,
      `┃ ${prefix}tagall [message] — mentionner les membres (max. 50)`,
      `┃ ${prefix}antilink on|off — bloquer les liens`,
      `┃ ${prefix}antiword on|off|add|remove|list — gérer les mots bloqués`,
      `┃ ${prefix}warn [reset] @membre — avertir / réinitialiser`,
      `┃ ${prefix}filter phrase = réponse — créer une réponse auto`,
      `┃ ${prefix}stop phrase — supprimer une réponse auto`,
      `┃ ${prefix}setgreet / ${prefix}setgoodbye message — configurer l’accueil`,
      `┃ ${prefix}getgreet / ${prefix}getgoodbye — voir les messages`,
      `┃ ${prefix}delgreet / ${prefix}delgoodbye — supprimer les messages`,
      `┃ ${prefix}kick / ${prefix}add @membre — gérer les membres`,
      `┃ ${prefix}promote / ${prefix}demote @membre — gérer les admins`,
      `┃ ${prefix}invite / ${prefix}revoke — gérer le lien du groupe`,
      `┃ ${prefix}mute / ${prefix}unmute — fermer / rouvrir le groupe`,
      '┣━━━━━━━━━━━━━━━━━━',
      '┃ ⚙️ *OPTIONS AUTOMATIQUES*',
      `┃ AUTO_STATUS : ${autoStatus}`,
      `┃ AUTO_UPDATE : ${autoUpdate}`,
      `┃ ${prefix}setvar AUTO_STATUS = on|off`,
      `┃ ${prefix}setvar AUTO_UPDATE = on|off`,
      '┣━━━━━━━━━━━━━━━━━━',
      '┃ 👑 *PROPRIÉTAIRE*',
      `┃ ${prefix}getvar NOM / ${prefix}allvar / ${prefix}delvar NOM`,
      `┃ ${prefix}update — mettre à jour le bot`,
      `┃ ${prefix}restart / ${prefix}shutdown — gérer le bot`,
      '╰━━━━━━━━━━━━━━━━━━',
      '_Les commandes admin nécessitent les droits du groupe ; les commandes propriétaire sont réservées au compte configuré._',
    ];
    await sendReply(menu.join('\n'));
  },
};
